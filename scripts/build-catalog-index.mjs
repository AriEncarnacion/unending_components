// Writes the agent-facing catalog index the plugin's skill reads:
// plugin/skills/unending-catalog/references/catalog.md, generated from
// registry.json and each entry's README. Run with --check to fail if stale.
import { existsSync, readFileSync, writeFileSync } from "node:fs"

const root = new URL("../", import.meta.url)
const registry = JSON.parse(readFileSync(new URL("registry.json", root), "utf8"))
const out = new URL("plugin/skills/unending-catalog/references/catalog.md", root)
const address = new URL(registry.homepage).pathname.slice(1)

function section(markdown, heading) {
  const match = markdown.match(new RegExp(`## ${heading}\\n([\\s\\S]*?)(?=\\n## |$)`))
  return match ? match[1].trim() : ""
}

const entries = registry.items.filter((item) => item.meta?.entry)
const lines = [
  "<!-- Generated by scripts/build-catalog-index.mjs from registry.json. Do not edit. -->",
  "# Unending catalog",
  "",
  `Registry: \`${address}\`. In a project linked to a design system (\`/unending:setup\`), install any entry with \`npx shadcn@latest add @unending/<name>\`; it arrives tuned for that system.`,
  "",
  "| Entry | Intent | Status |",
  "| --- | --- | --- |",
  ...entries.map((item) => `| \`${item.name}\` | ${item.meta.intent} | ${item.meta.status} |`),
  "",
]

for (const item of entries) {
  const readmeUrl = new URL(`registry/unending/${item.name}/README.md`, root)
  const readme = existsSync(readmeUrl) ? readFileSync(readmeUrl, "utf8") : ""
  lines.push(
    `## ${item.title} (\`${item.name}\`)`,
    "",
    `**Intent:** ${item.meta.intent}`,
    "",
    item.description,
    "",
    `**Use when:**`,
    "",
    section(readme, "When to use") || "_See the entry README._",
    "",
    `**Built from:** ${(item.registryDependencies ?? []).filter((d) => !d.includes("/")).map((d) => `\`${d}\``).join(", ")}`,
    "",
    item.docs ? `**After installing:** ${item.docs}` : "",
    "",
    `**Install:** \`npx shadcn@latest add ${address}/${item.name}\``,
    "",
  )
}

const content = lines.filter((line, index, all) => !(line === "" && all[index - 1] === "")).join("\n")

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : ""
  if (current !== content) {
    console.error("Catalog index is stale. Run npm run registry:index.")
    process.exit(1)
  }
  console.log("Catalog index in sync.")
} else {
  writeFileSync(out, content)
  console.log(`Wrote ${entries.length} entries to ${out.pathname}`)
}
